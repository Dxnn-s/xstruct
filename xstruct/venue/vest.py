"""Vest read-path adapter.

Vest (vest.exchange / vestmarkets.com) runs perpetual futures on crypto, stocks,
ETFs and forex, USDC-margined. Public REST, no key needed for reads.

The documented base URL (serverprod.vest.exchange/v2) answered with a Cloudflare
origin error on 2026-10-15; the live host below was taken from the trading app's
own bundle. Shapes verified live the same day:
  GET /exchangeInfo            -> {"symbols":[{"symbol","displayName","asset","tradingStatus",...}]}
  GET /depth?symbol=&limit=    -> {"bids":[[px,sz],...],"asks":[[px,sz],...],"ts_ms"}
  GET /trades?symbol=&limit=   -> [{"id","price","qty","quoteQty","time"}]  (no aggressor side)

Two things worth knowing. The depth endpoint returned a uniform 0.0001-size
ladder at one-tick steps on BTC-PERP, which reads like quotes generated by their
risk engine rather than resting orders, so size at depth means less here than on
a central limit book. And trades carry no side, so `Trade.side` is "unknown";
nothing downstream should infer aggressor from it.

Both sides of the book are sorted here rather than trusting wire order.
"""
from __future__ import annotations

from typing import Callable

from .base import Book, Level, Market, Trade, Venue

BASE_URL = "https://server-prod.hz.vestmarkets.com/v2"


class VestVenue(Venue):
    name = "vest"

    def __init__(
        self,
        symbols: list[str] | None = None,
        timeout: float = 8.0,
        get_fn: Callable[[str, dict], object] | None = None,
    ) -> None:
        self._symbols = symbols  # optional filter; None = every TRADING symbol
        self._timeout = timeout
        self._get = get_fn or self._http_get
        self._client = None

    def _http_get(self, path: str, params: dict) -> object:
        import httpx

        if self._client is None:
            self._client = httpx.Client(timeout=self._timeout, headers={"Accept": "application/json"})
        r = self._client.get(BASE_URL + path, params=params)
        r.raise_for_status()
        return r.json()

    def close(self) -> None:
        if self._client is not None:
            self._client.close()
            self._client = None

    def get_markets(self) -> list[Market]:
        data = self._get("/exchangeInfo", {})
        out: list[Market] = []
        for s in data.get("symbols", []):
            if s.get("tradingStatus") != "TRADING":
                continue
            sym = s["symbol"]
            if self._symbols and sym not in self._symbols:
                continue
            desc = f"Vest {s.get('asset', 'perp')} perp {s.get('displayName') or sym}"
            out.append(Market(venue=self.name, symbol=sym, description=desc, kind="perp"))
        return out

    def get_book(self, symbol: str, depth: int = 10) -> Book:
        data = self._get("/depth", {"symbol": symbol, "limit": depth})
        bids = sorted((Level(float(p), float(q)) for p, q in data.get("bids", [])), key=lambda l: -l.price)
        asks = sorted((Level(float(p), float(q)) for p, q in data.get("asks", [])), key=lambda l: l.price)
        ts = float(data.get("ts_ms", 0)) / 1000.0
        return Book(venue=self.name, symbol=symbol, ts=ts, bids=bids[:depth], asks=asks[:depth])

    def get_trades(self, symbol: str, limit: int = 50) -> list[Trade]:
        data = self._get("/trades", {"symbol": symbol, "limit": limit})
        return [
            Trade(
                venue=self.name,
                symbol=symbol,
                ts=float(t.get("time", 0)) / 1000.0,
                price=float(t["price"]),
                size=float(t["qty"]),
                side="unknown",
            )
            for t in list(data)[:limit]
        ]
